#!/usr/bin/env bash
set -Eeuo pipefail

repo_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
source_repo="${CURSOR_PLUGINS_REPO:-https://github.com/cursor/plugins.git}"
source_ref="${CURSOR_PLUGINS_REF:-main}"
skill="thermo-nuclear-code-quality-review"
source_path="cursor-team-kit/skills/$skill"
destination_dir="$repo_dir/agents/skills/$skill"
temporary_dir="$(mktemp -d /tmp/configs-cursor-team-kit.XXXXXX)"

cleanup() {
  rm -rf "$temporary_dir"
}
trap cleanup EXIT

for command in git rsync; do
  if ! command -v "$command" >/dev/null 2>&1; then
    echo "$command is required to update the Cursor team kit skill" >&2
    exit 1
  fi
done

git clone \
  --quiet \
  --depth=1 \
  --filter=blob:none \
  --branch "$source_ref" \
  --sparse \
  "$source_repo" \
  "$temporary_dir/source"

git -C "$temporary_dir/source" sparse-checkout set --no-cone \
  "/$source_path/" \
  "/cursor-team-kit/LICENSE"

source_dir="$temporary_dir/source/$source_path"
if [[ ! -f "$source_dir/SKILL.md" ]]; then
  echo "Cursor team kit skill is missing SKILL.md" >&2
  exit 1
fi

mkdir -p "$destination_dir"
rsync --archive --delete "$source_dir/" "$destination_dir/"
cp "$temporary_dir/source/cursor-team-kit/LICENSE" "$destination_dir/LICENSE"

source_commit="$(git -C "$temporary_dir/source" rev-parse HEAD)"
printf '%s\n' \
  '# Generated by agents/sync-cursor-team-kit.sh' \
  "repository=$source_repo" \
  "ref=$source_ref" \
  "path=$source_path" \
  "commit=$source_commit" \
  >"$repo_dir/agents/cursor-team-kit.lock"

printf 'Pinned Cursor team kit skill at %s\n' "$source_commit"
